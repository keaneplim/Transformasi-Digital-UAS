import 'package:jelajah_taman/core/core.dart';

import 'map_geometry.dart';

/// One closed area (landcover, water, building) with optional holes.
class BaseArea {
  const BaseArea(this.kind, this.ring, [this.holes = const []]);

  final String kind;
  final List<GeoPoint> ring;
  final List<List<GeoPoint>> holes;
}

/// One line (road, path, waterway, contour).
class BaseLine {
  const BaseLine(this.kind, this.points, {this.name, this.elevationM});

  final String kind;
  final List<GeoPoint> points;
  final String? name;

  /// Contours only.
  final double? elevationM;
}

class BaseLabel {
  const BaseLabel(this.text, this.kind, this.position);

  final String text;
  final String kind;
  final GeoPoint position;
}

/// The bundled offline basemap (A01), generated by tools/osm_to_basemap.py from OpenStreetMap
/// (ODbL) and a terrain grid. Pure data: the map widget decides how it looks.
class BasemapData {
  BasemapData({
    required this.bounds,
    required this.landcover,
    required this.water,
    required this.boundary,
    required this.buildings,
    required this.waterways,
    required this.roads,
    required this.paths,
    required this.contours,
    required this.labels,
    required this.sources,
    this.hillshadeFile,
    this.hillshadeBounds,
    this.indexStepM = 50,
  });

  factory BasemapData.fromJson(Map<String, Object?> j) {
    List<GeoPoint> pts(Object? flat) {
      final l = (flat! as List<Object?>).cast<num>();
      return [
        for (var i = 0; i + 1 < l.length; i += 2)
          GeoPoint(l[i].toDouble(), l[i + 1].toDouble())
      ];
    }

    List<Map<String, Object?>> list(String k) =>
        ((j[k] as List<Object?>?) ?? const []).cast<Map<String, Object?>>();

    GeoBounds box(Object? b) {
      final l = (b! as List<Object?>).cast<num>();
      return GeoBounds(
          south: l[0].toDouble(),
          west: l[1].toDouble(),
          north: l[2].toDouble(),
          east: l[3].toDouble());
    }

    BaseArea area(Map<String, Object?> m, [String fallback = '']) => BaseArea(
          (m['k'] as String?) ?? fallback,
          pts(m['r']),
          [for (final h in (m['h'] as List<Object?>?) ?? const []) pts(h)],
        );

    final hill = j['hillshade'] as Map<String, Object?>?;
    return BasemapData(
      bounds: box(j['bounds']),
      landcover: [for (final m in list('landcover')) area(m)],
      water: [for (final m in list('water')) area(m, 'water')],
      boundary: [
        for (final r in (j['boundary'] as List<Object?>?) ?? const []) pts(r)
      ],
      buildings: [
        for (final r in (j['buildings'] as List<Object?>?) ?? const [])
          BaseArea('building', pts(r))
      ],
      waterways: [
        for (final m in list('waterways'))
          BaseLine(m['k']! as String, pts(m['p']), name: m['n'] as String?)
      ],
      roads: [
        for (final m in list('roads'))
          BaseLine(m['k']! as String, pts(m['p']), name: m['n'] as String?)
      ],
      paths: [
        for (final m in list('paths')) BaseLine(m['k']! as String, pts(m['p']))
      ],
      contours: [
        for (final m in list('contours'))
          BaseLine('contour', pts(m['p']),
              elevationM: (m['e']! as num).toDouble())
      ],
      labels: [
        for (final m in list('labels'))
          BaseLabel(
              m['t']! as String,
              m['k']! as String,
              GeoPoint(((m['p']! as List)[0] as num).toDouble(),
                  ((m['p']! as List)[1] as num).toDouble()))
      ],
      sources: ((j['sources'] as List<Object?>?) ?? const []).cast<String>(),
      hillshadeFile: hill?['file'] as String?,
      hillshadeBounds: hill == null ? null : box(hill['bounds']),
      indexStepM: ((j['index_step'] as num?) ?? 50).toDouble(),
    );
  }

  final GeoBounds bounds;
  final List<BaseArea> landcover;
  final List<BaseArea> water;
  final List<List<GeoPoint>> boundary;
  final List<BaseArea> buildings;
  final List<BaseLine> waterways;
  final List<BaseLine> roads;
  final List<BaseLine> paths;
  final List<BaseLine> contours;
  final List<BaseLabel> labels;
  final List<String> sources;
  final String? hillshadeFile;
  final GeoBounds? hillshadeBounds;
  final double indexStepM;

  bool isIndexContour(BaseLine c) => (c.elevationM ?? 0) % indexStepM == 0;
}
